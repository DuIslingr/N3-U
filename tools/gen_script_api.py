"""Generate engine/src/script/game_api_names.inc: the names of every C function the game
registers with Lua (functions taking a lua_State* in libNOVA3_neon.so's symbol table).

The engine registers all of them so level scripts never call nil; the ones it does
not implement yet log their first use and return nothing.

    python3 tools/gen_script_api.py work/bin/libNOVA3_neon.so
"""
import re
import subprocess
import sys
from pathlib import Path


def main(argv):
    lib = argv[1] if len(argv) > 1 else "work/bin/libNOVA3_neon.so"
    out = subprocess.run(["nm", "-C", lib], capture_output=True, text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        m = re.match(r"^[0-9a-f]+ [tT] ([A-Za-z_][A-Za-z0-9_]*)\(lua_State\*\)$", line)
        if m and not re.match(r"lua[A-Z_]|luaopen|lua_", m.group(1)):
            names.add(m.group(1))
    dest = Path(__file__).resolve().parent.parent / "engine/src/script/game_api_names.inc"
    body = "".join(f'"{n}",\n' for n in sorted(names))
    dest.write_text("// Generated by tools/gen_script_api.py: Lua functions the game registers.\n" + body)
    print(f"{len(names)} names -> {dest}")


if __name__ == "__main__":
    main(sys.argv)
