#!/usr/bin/env python3
"""Generate engine/src/assets/level_specs.inc from tools/lvc_specs.py and lvc.py.

The engine and the Python tools then share one source of truth for the level and
object-library read specs. Run after regenerating lvc_specs.py.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import lvc  # noqa: E402
import lvc_specs  # noqa: E402

OUT = ROOT.parent / "engine" / "src" / "assets" / "level_specs.inc"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = [
        "// Generated by tools/gen_engine_specs.py from tools/lvc_specs.py and tools/lvc.py.",
        "// Do not edit; regenerate instead.",
        "// Spec tokens: i f h H c s v, [ ... ] = int-count-prefixed list, <Name::Load> = nested loader.",
        "",
        "// CComponentFactory::CreateComponent: component id -> runtime class.",
        "static const std::pair<int, const char*> kComponentClasses[] = {",
    ]
    lines += [f"    {{{cid:#04x}, {cstr(name)}}}," for cid, name in sorted(lvc_specs.COMPONENT_CLASSES.items())]
    lines += ["};", "", "// GenerateComponentTemplate: component id -> template spec (gol.bin).",
              "static const std::pair<int, const char*> kTemplateSpecs[] = {"]
    lines += [f"    {{{cid:#04x}, {cstr(spec)}}}," for cid, spec in sorted(lvc_specs.TEMPLATE_SPECS.items())]
    specs = dict(lvc_specs.SPECS)
    specs.update(lvc.SPEC_OVERRIDES)
    lines += ["};", "", "// Loader name -> spec (generated specs with lvc.SPEC_OVERRIDES applied).",
              "static const std::pair<const char*, const char*> kLoaderSpecs[] = {"]
    lines += [f"    {{{cstr(k)}, {cstr(v)}}}," for k, v in sorted(specs.items())]
    lines += ["};", "", "// CreateObject components read whatever their flag (config components).",
              "static const std::pair<int, const char*> kAlwaysSpecs[] = {"]
    lines += [f"    {{{cid:#04x}, {cstr(spec)}}}," for cid, spec in sorted(lvc.ALWAYS.items())]
    lines += ["};", "", "// Inline per-instance readers in CreateObject (besides base 0x00 and mesh 0x01).",
              "static const std::pair<int, const char*> kPerInstanceSpecs[] = {"]
    lines += [f"    {{{cid:#04x}, {cstr(spec)}}}," for cid, spec in sorted(lvc.PER_INSTANCE.items()) if cid > 1]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(specs)} loader specs)")


if __name__ == "__main__":
    main()
