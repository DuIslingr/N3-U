#!/usr/bin/env python3
"""Regenerate tools/lvc_specs.py from work/decomp/specs.json, template_specs.json and component_ids.txt.

Pipeline: Decomp.java -> skel2spec.py -> specs.json; gen_templates.py -> template_specs.json; then this.
Run from the repository root.
"""
import json, re
specs = json.load(open('work/decomp/specs.json'))
ids = {int(a, 16): b for a, b in (l.split() for l in open('work/decomp/component_ids.txt'))}
templates = {int(k, 16): v['spec'] for k, v in json.load(open('work/decomp/template_specs.json')).items()}
need = set(); stack = [f'{c}::Load' for c in ids.values()]
for t in templates.values(): stack += re.findall(r'<([^>]+)>', t)
while stack:
    k = stack.pop()
    if k in need or k not in specs: continue
    need.add(k); stack += re.findall(r'<([^>]+)>', specs[k]['spec'])
lines = ['"""Read specs for game-object components in .lvc files.', '',
         'Generated by tools/ghidra_scripts/skel2spec.py from the game\'s decompiled',
         'loaders (CComponentFactory::CreateComponent and each component\'s',
         'Load(CMemoryStream*)). Tokens: i f h c s v, [ ... ] = int-count-prefixed list,',
         '<Name::Load> = nested loader. Do not edit by hand; regenerate instead (hand',
         'corrections go in lvc.SPEC_OVERRIDES).', '"""', '', 'COMPONENT_CLASSES = {']
lines += [f'    {c:#04x}: "{n}",' for c, n in sorted(ids.items())]
lines += ['}', '', '# GenerateComponentTemplate: component id -> template data read from gol.bin', 'TEMPLATE_SPECS = {']
lines += [f'    {c:#04x}: "{t}",' for c, t in sorted(templates.items())]
lines += ['}', '', 'SPECS = {'] + [f'    "{k}": "{specs[k]["spec"]}",' for k in sorted(need)] + ['}', '']
open('tools/lvc_specs.py', 'w').write('\n'.join(lines))
missing = sorted({f'{c}::Load' for c in ids.values()} - set(specs))
print('classes', len(ids), 'specs', len(need), 'classes without a Load:', missing)
